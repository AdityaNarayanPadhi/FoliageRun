import { Waypoint } from '../types/route';

/**
 * Escapes characters for safe XML inclusion.
 */
function escapeXml(unsafe: string): string {
  return unsafe
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

export interface GpxOptions {
  routeTitle?: string;
  description?: string;
  creator?: string;
  startTime?: Date;
  averagePaceMinPerKm?: number;
}

/**
 * Converts synthesized waypoint array into valid, standards-compliant GPX 1.1 XML.
 * Compatible with Garmin Connect, Strava, Apple Watch Workout, and Komoot.
 */
export function generateGpxXml(
  waypoints: Waypoint[],
  options: GpxOptions = {}
): string {
  const {
    routeTitle = 'FoliageRun Autumn Route',
    description = 'Synthesized scenic autumn running route generated by FoliageRun for Hacktoberfest 2026',
    creator = 'FoliageRun Touch Grass Engine v1.0',
    startTime = new Date(),
    averagePaceMinPerKm = 5.5, // 5:30 min/km pace
  } = options;

  const nowIso = startTime.toISOString();
  let currentTimeMs = startTime.getTime();

  const xmlHeader = '<?xml version="1.0" encoding="UTF-8"?>';
  const gpxOpen = [
    '<gpx version="1.1"',
    ` creator="${escapeXml(creator)}"`,
    ' xmlns="http://www.topografix.com/GPX/1/1"',
    ' xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"',
    ' xsi:schemaLocation="http://www.topografix.com/GPX/1/1 http://www.topografix.com/GPX/1/1/gpx.xsd"',
    '>',
  ].join('');

  const metadata = [
    '  <metadata>',
    `    <name>${escapeXml(routeTitle)}</name>`,
    `    <desc>${escapeXml(description)}</desc>`,
    '    <author>',
    '      <name>FoliageRun Agent</name>',
    '    </author>',
    `    <time>${nowIso}</time>`,
    '  </metadata>',
  ].join('\n');

  // Individual waypoints (POI markers for navigation watches)
  const waypointsXml = waypoints
    .map((wp, idx) => {
      const eleXml = wp.ele !== undefined ? `\n    <ele>${wp.ele.toFixed(1)}</ele>` : '';
      return [
        `  <wpt lat="${wp.lat.toFixed(6)}" lon="${wp.lng.toFixed(6)}">${eleXml}`,
        `    <name>${escapeXml(wp.name || `Waypoint ${idx + 1}`)}</name>`,
        '    <sym>Scenic Area</sym>',
        '    <type>Foliage Checkpoint</type>',
        '  </wpt>',
      ].join('');
    })
    .join('\n');

  // Continuous track segment with simulated timestamps for Strava / Garmin pacing
  const trackpointsXml = waypoints
    .map((wp, idx) => {
      // Advance time by ~30 seconds per waypoint increment
      const ptTime = new Date(currentTimeMs + idx * 30000).toISOString();
      const eleXml = wp.ele !== undefined ? `\n        <ele>${wp.ele.toFixed(1)}</ele>` : '';
      return [
        `      <trkpt lat="${wp.lat.toFixed(6)}" lon="${wp.lng.toFixed(6)}">${eleXml}`,
        `        <time>${ptTime}</time>`,
        '      </trkpt>',
      ].join('');
    })
    .join('\n');

  const track = [
    '  <trk>',
    `    <name>${escapeXml(routeTitle)}</name>`,
    `    <desc>${escapeXml(description)}</desc>`,
    '    <type>Running</type>',
    '    <trkseg>',
    trackpointsXml,
    '    </trkseg>',
    '  </trk>',
  ].join('\n');

  return [
    xmlHeader,
    gpxOpen,
    metadata,
    waypointsXml,
    track,
    '</gpx>',
  ].join('\n');
}
